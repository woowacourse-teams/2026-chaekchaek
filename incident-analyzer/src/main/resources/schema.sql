CREATE TABLE IF NOT EXISTS incident_job (
    id VARCHAR(255) PRIMARY KEY,
    environment VARCHAR(255) NOT NULL,
    alert_name VARCHAR(255) NOT NULL,
    profile VARCHAR(255) NOT NULL,
    starts_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deadline_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    lease_until TIMESTAMP(6) WITH TIME ZONE,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved BOOLEAN NOT NULL,
    work_state VARCHAR(255) NOT NULL,
    attempts INTEGER NOT NULL,
    delivery_attempts INTEGER NOT NULL,
    result_json CLOB,
    failure_code VARCHAR(100)
);
CREATE INDEX IF NOT EXISTS incident_work_idx ON incident_job(work_state, next_attempt_at);
CREATE TABLE IF NOT EXISTS incident (
    id VARCHAR(255) PRIMARY KEY,
    environment VARCHAR(255) NOT NULL,
    alert_name VARCHAR(255) NOT NULL,
    profile VARCHAR(255) NOT NULL,
    starts_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    resolved BOOLEAN NOT NULL
);
INSERT INTO incident (id, environment, alert_name, profile, starts_at, received_at, resolved)
SELECT j.id, j.environment, j.alert_name, j.profile, j.starts_at, j.received_at, j.resolved
FROM incident_job j WHERE NOT EXISTS (SELECT 1 FROM incident i WHERE i.id = j.id);
CREATE TABLE IF NOT EXISTS model_call (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserved_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS question_job (
    id VARCHAR(255) PRIMARY KEY,
    environment VARCHAR(255) NOT NULL,
    channel VARCHAR(255) NOT NULL,
    thread_ts VARCHAR(255) NOT NULL,
    question VARCHAR(2000) NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    deadline_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    lease_until TIMESTAMP(6) WITH TIME ZONE,
    next_attempt_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    work_state VARCHAR(255) NOT NULL,
    attempts INTEGER NOT NULL,
    delivery_attempts INTEGER NOT NULL,
    result_json CLOB,
    failure_code VARCHAR(100)
);
CREATE INDEX IF NOT EXISTS question_work_idx ON question_job(work_state, next_attempt_at);
CREATE INDEX IF NOT EXISTS question_thread_idx ON question_job(channel, thread_ts, received_at);
